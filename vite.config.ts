/// <reference types="vitest/config" />
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { VitePWA } from 'vite-plugin-pwa';
import { defineConfig, type Plugin } from 'vite';
import { fileURLToPath, URL } from 'node:url';
import { readFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as { version: string };
const ortVersion = (
  JSON.parse(readFileSync(new URL('./node_modules/onnxruntime-web/package.json', import.meta.url), 'utf8')) as { version: string }
).version;

/**
 * ONNX Runtime references its 27 MB WebAssembly binary with new URL(…, import.meta.url), which
 * would copy it into the build (and the APK). Przystań downloads it only after the user agreed
 * to download a local model (src/lib/ai/local) – so the reference points to the pinned CDN file.
 */
const ortWasmFromCdn = (): Plugin => ({
  name: 'ort-wasm-from-cdn',
  enforce: 'pre',
  transform(code, id) {
    if (!/onnxruntime-web[\\/]dist[\\/].*\.mjs$/.test(id)) return null;
    const out = code.replace(
      /new URL\((["'])(ort-wasm-simd-threaded(?:\.\w+)?\.wasm)\1,\s*import\.meta\.url\)/g,
      (_m, _q, file: string) => `new URL("https://cdn.jsdelivr.net/npm/onnxruntime-web@${ortVersion}/dist/${file}")`,
    );
    return out === code ? null : { code: out, map: null };
  },
});

/** AI code (Transformers.js, WebLLM, pdf.js, workers) gets an "ai-" prefix: excluded from the PWA precache. */
const AI_MODULE = /node_modules[\\/](?:@huggingface|@mlc-ai|onnxruntime-web|onnxruntime-common|pdfjs-dist)[\\/]/;
const isAiChunk = (ids: string[]) => ids.length > 0 && ids.every((m) => AI_MODULE.test(m));

// The app uses hash routing and relative asset paths, so the same build works
// on GitHub Pages (any sub-path) and inside the Capacitor Android WebView.
export default defineConfig({
  base: './',
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  plugins: [
    {
      // inject iOS splash screen links generated by `npm run assets`
      name: 'apple-splash-links',
      transformIndexHtml: (html) =>
        html.replace('<!--SPLASH-->', readFileSync(new URL('./scripts/splash-links.html', import.meta.url), 'utf8')),
    },
    ortWasmFromCdn(),
    react(),
    tailwindcss(),
    VitePWA({
      registerType: 'prompt',
      injectRegister: false,
      includeAssets: ['favicon.svg', 'apple-touch-icon-180x180.png', 'splash/*.png'],
      manifest: {
        id: './',
        name: 'Przystań – Harbor',
        short_name: 'Przystań',
        description:
          'Narzędzie offline dla pedagoga resocjalizacyjnego i specjalisty ds. uzależnień. Offline tool for social rehabilitation educators and addiction specialists.',
        lang: 'pl',
        start_url: './',
        scope: './',
        display: 'standalone',
        orientation: 'any',
        background_color: '#f6f1ea',
        theme_color: '#4f6f5c',
        categories: ['education', 'productivity'],
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          { src: 'maskable-icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        globPatterns: ['**/*.{js,css,html,svg,png,woff2,webmanifest}'],
        // optional AI code is fetched only when used (then cached at runtime, see below)
        globIgnores: ['**/lazy-ai-*'],
        runtimeCaching: [
          {
            urlPattern: ({ url }) => /\/(?:assets\/lazy-ai-|ort\/)/.test(url.pathname),
            handler: 'CacheFirst',
            options: { cacheName: 'przystan-ai-code', expiration: { maxEntries: 40 } },
          },
        ],
        maximumFileSizeToCacheInBytes: 8 * 1024 * 1024,
        navigateFallback: 'index.html',
        cleanupOutdatedCaches: true,
      },
    }),
  ],
  build: {
    target: 'es2022',
    // WebLLM (≈ 6 MB) is loaded only after the user downloaded the local language model
    chunkSizeWarningLimit: 6500,
    rollupOptions: {
      output: {
        chunkFileNames: (c) => (isAiChunk(c.moduleIds) ? 'assets/lazy-ai-[name]-[hash].js' : 'assets/[name]-[hash].js'),
        assetFileNames: (a) =>
          /pdf\.worker/.test(a.names?.[0] ?? '') ? 'assets/lazy-ai-[name]-[hash][extname]' : 'assets/[name]-[hash][extname]',
      },
    },
  },
  worker: {
    format: 'es',
    plugins: () => [ortWasmFromCdn()],
    rollupOptions: {
      output: {
        entryFileNames: 'assets/lazy-ai-[name]-[hash].js',
        chunkFileNames: 'assets/lazy-ai-[name]-[hash].js',
      },
    },
  },
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./src/test/setup.ts'],
    include: ['src/**/*.test.{ts,tsx}'],
    testTimeout: 30000,
    // content tests glob JSON files; a persisted module cache would miss new files
    fsModuleCache: false,
  },
});
